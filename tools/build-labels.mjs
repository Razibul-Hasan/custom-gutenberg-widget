// Writes src/blocks/shared/style-labels.js: every Styles-tab text of every block.json (setting labels, panel names,
// select options) as a literal __() call, so WordPress' translation tools (wp i18n make-pot, Loco Translate,
// translate.wordpress.org) find them and the Styles tab shows them in the site's language.
// Run by `npm run build` / `npm run start` before webpack.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve( dirname( fileURLToPath( import.meta.url ) ), '..' );
const BLOCKS = join( ROOT, 'src/blocks' );
const texts = new Set();
for ( const dir of readdirSync( BLOCKS ) ) {
	const file = join( BLOCKS, dir, 'block.json' );
	if ( ! existsSync( file ) ) {
		continue;
	}
	for ( const s of JSON.parse( readFileSync( file, 'utf8' ) ).bweStyleMap || [] ) {
		[ s.label, s.panel, s.help, ...( s.options || [] ).map( ( o ) => o.label ) ]
			.filter( ( t ) => typeof t === 'string' && t.trim() )
			.forEach( ( t ) => texts.add( t ) );
	}
}
const lines = [ ...texts ]
	.sort( ( a, b ) => a.localeCompare( b ) )
	.map( ( t ) => `\t${ JSON.stringify( t ) }: __( ${ JSON.stringify( t ) }, 'bestwebexpert' ),` );
writeFileSync(
	join( BLOCKS, 'shared/style-labels.js' ),
	`// Generated by tools/build-labels.mjs from the blocks' bweStyleMap — do not edit by hand.\n` +
		`import { __ } from '@wordpress/i18n';\n\n` +
		`const LABELS = {\n${ lines.join( '\n' ) }\n};\n\n` +
		`/**\n * The translated Styles-tab text (falls back to the English text).\n *\n * @param {string} text English text from block.json.\n * @return {string} Translated text.\n */\n` +
		`export default function styleLabel( text ) {\n\treturn ( text && LABELS[ text ] ) || text;\n}\n`
);
console.log( `style-labels.js: ${ texts.size } texts` );
