// Writes assets/css/heading-compat.css: the site styles some headings by their tag (the call to action's
// "h2.wp-block-heading", in several files and palettes). When a block's "Heading tag (SEO)" setting prints that
// heading as h3 / p / div …, these copies of exactly those rules keep its look — same declarations, same media
// queries, same order and specificity (h2 → :is(h1, h3, …) weighs the same as h2).
// Source: BestWebExpert Home's stylesheets, in the order the site loads them. Run: npm run heading-compat
// (also part of npm run build). Re-run after changing the CTA's CSS in BestWebExpert Home.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve( dirname( fileURLToPath( import.meta.url ) ), '..' );
const HOME = resolve( ROOT, '../bestwebexpert-home/assets' );
// Front-end load order (home.css → bundle → final-cta.css); see the page's <link> tags.
// The theme's site-font.css (Appearance → site font) comes last: it sets the CTA heading's weight and spacing.
const FILES = [ 'home.css', 'home-2/bundle/bundle.min.css', 'final-cta.css', 'service-match.css', resolve( ROOT, '../../themes/astra-child/assets/site-font.css' ) ];
// Selectors to copy: a heading styled by its tag inside the call to action (.bwe-final, .bwe-final__box).
const MATCH = /\.bwe-final[\w-]*[^,{]*(?:\s|>)\s*h2(?![\w-])/;
const OTHER = ':is(h1, h3, h4, h5, h6, p, div)';

/** Splits CSS into [ { media, selector, body } ] (one level of @media / @supports nesting is enough here). */
function rules( css, media = '' ) {
	const out = [];
	css = css.replace( /\/\*[\s\S]*?\*\//g, '' );
	let i = 0;
	while ( i < css.length ) {
		const open = css.indexOf( '{', i );
		if ( open < 0 ) break;
		const head = css.slice( i, open ).trim();
		let depth = 1;
		let j = open + 1;
		while ( j < css.length && depth ) {
			if ( css[ j ] === '{' ) depth++;
			else if ( css[ j ] === '}' ) depth--;
			j++;
		}
		const body = css.slice( open + 1, j - 1 );
		if ( /^@(media|supports)/.test( head ) ) {
			out.push( ...rules( body, head ) );
		} else if ( ! head.startsWith( '@' ) ) {
			out.push( { media, selector: head, body: body.trim() } );
		}
		i = j;
	}
	return out;
}

// Splits a selector list on top-level commas (not the ones inside :is() / :not()).
const split = ( list ) => {
	const parts = [];
	let depth = 0;
	let cur = '';
	for ( const ch of list ) {
		if ( ch === '(' ) depth++;
		if ( ch === ')' ) depth--;
		if ( ch === ',' && ! depth ) {
			parts.push( cur.trim() );
			cur = '';
		} else cur += ch;
	}
	if ( cur.trim() ) parts.push( cur.trim() );
	return parts;
};

let css = '';
let count = 0;
for ( const file of FILES ) {
	const path = file.includes( ':' ) || file.startsWith( '/' ) ? file : join( HOME, file );
	if ( ! existsSync( path ) ) continue;
	for ( const r of rules( readFileSync( path, 'utf8' ) ) ) {
		const sels = split( r.selector ).filter( ( s ) => MATCH.test( s ) ).map( ( s ) => s.replace( /((?:\s|>)\s*)h2(?![\w-])(\.wp-block-heading)?/g, `$1${ OTHER }.wp-block-heading` ) ); // the class keeps it to the heading itself
		if ( ! sels.length ) continue;
		const rule = `${ sels.join( ',\n' ) } {${ r.body }}`;
		css += r.media ? `${ r.media } {\n${ rule }\n}\n` : `${ rule }\n`;
		count++;
	}
}
writeFileSync(
	join( ROOT, 'assets/css/heading-compat.css' ),
	`/* Generated by tools/build-heading-compat.mjs from BestWebExpert Home's CSS — do not edit by hand. */\n${ css }`
);
console.log( `heading-compat.css: ${ count } rules` );
